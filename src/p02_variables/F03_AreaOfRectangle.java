package p02_variables;

public class F03_AreaOfRectangle {
    static void main(String[] args){
        int length = 5;
        int width = 6;
        int area;
        area = length * width;
        System.out.println("Length is " + length);
        System.out.println("Width is " + width);
        System.out.println("Area is " + area);
    }
}
